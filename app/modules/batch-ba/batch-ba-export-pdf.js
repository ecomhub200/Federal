/**
 * CrashLens Batch Before/After Evaluation — PDF Report Export
 * Professional multi-page PDF with executive summary, TOC, charts, and callout boxes.
 * Uses jsPDF + AutoTable with hex color palette, section accent bars, severity bars, and KPI cards.
 */
window.CL = window.CL || {};
CL.batchBA = CL.batchBA || {};

/**
 * Generate and download batch BA PDF report.
 */
CL.batchBA.exportPDF = function() {
    var s = CL.batchBA.state;
    if (!s.summary || s.results.length === 0) {
        alert('No results to export. Run the batch analysis first.');
        return;
    }

    var jsPDF = window.jspdf.jsPDF;
    var doc = new jsPDF('p', 'mm', 'letter');
    var pw = 215.9;
    var ph = 279.4;
    var m = 18;
    var cw = pw - m * 2;
    var footerH = 20;
    var headerH = 12;
    var safeBottom = ph - footerH - 5;

    var C = {
        primary: '#1E3A5F', primaryLight: '#2563eb',
        text: '#374151', textLight: '#6b7280',
        fatal: '#991B1B', fatalLight: '#dc2626',
        serious: '#C2410C', moderate: '#f97316',
        minor: '#facc15', pdo: '#9CA3AF',
        success: '#065f46', successLight: '#16a34a',
        danger: '#dc2626', warning: '#ea580c',
        white: '#ffffff', gray: '#9CA3AF',
        border: '#e5e7eb', lightBg: '#f8fafc',
        secondary: '#7c3aed'
    };

    var successful = s.results.filter(function(r) { return r.status === 'success'; });
    var sum = s.summary;

    // Run validation before generating PDF
    if (typeof CL.batchBA._validateSummary === 'function') {
        CL.batchBA._validateSummary();
    }
    var dateStamp = new Date().toISOString().split('T')[0];
    var generatedDate = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
    var fips = (typeof getCurrentStateFips === 'function') ? getCurrentStateFips() : '_default';
    var epdoInfo = CL.core.epdo.getStateEPDOWeights(fips);
    var pageNum = 0;
    var y = m + headerH;
    var sectionPages = {}; // Track section page numbers for TOC

    // === HELPER FUNCTIONS ===
    function hexToRgb(hex) {
        var result = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex);
        return result ? { r: parseInt(result[1], 16), g: parseInt(result[2], 16), b: parseInt(result[3], 16) } : { r: 0, g: 0, b: 0 };
    }
    function setColor(hex) { var rgb = hexToRgb(hex); doc.setTextColor(rgb.r, rgb.g, rgb.b); }
    function setFill(hex) { var rgb = hexToRgb(hex); doc.setFillColor(rgb.r, rgb.g, rgb.b); }
    function cleanText(text) {
        if (!text) return '';
        var s = String(text);
        // Fix common mojibake: UTF-8 bytes misinterpreted as Latin-1/Windows-1252
        s = s.replace(/\u00e2\u0080\u0093/g, '-');   // â€" → en-dash → hyphen
        s = s.replace(/\u00e2\u0080\u0094/g, '-');   // â€" → em-dash → hyphen
        s = s.replace(/\u00e2\u0080\u0099/g, "'");   // â€™ → right single quote
        s = s.replace(/\u00e2\u0080\u009c/g, '"');   // â€œ → left double quote
        s = s.replace(/\u00e2\u0080\u009d/g, '"');   // â€ → right double quote
        s = s.replace(/\u00e2\u0080\u00a6/g, '...');  // â€¦ → ellipsis
        s = s.replace(/\u00c3\u00a9/g, 'e');          // Ã© → é → e
        // Also fix string-level mojibake patterns (when already decoded as text)
        s = s.replace(/â€"/g, '-').replace(/â€"/g, '-');
        s = s.replace(/â€™/g, "'").replace(/â€˜/g, "'");
        s = s.replace(/â€œ/g, '"').replace(/â€\u009d/g, '"');
        s = s.replace(/â€¦/g, '...');
        // Standard Unicode normalization
        s = s.replace(/[\u2018\u2019\u0060\u00B4]/g, "'").replace(/[\u201C\u201D]/g, '"');
        s = s.replace(/[\u2013\u2014\u2012]/g, '-').replace(/[\u2026]/g, '...');
        s = s.replace(/[\u00A0]/g, ' ').replace(/[^\x00-\x7F]/g, '').replace(/\s+/g, ' ');
        return s.trim();
    }
    function drawPageHeader() {
        var rgb = hexToRgb(C.primary);
        doc.setFillColor(rgb.r, rgb.g, rgb.b);
        doc.rect(0, 0, pw, headerH, 'F');
        doc.setFontSize(9); doc.setFont('helvetica', 'bold'); doc.setTextColor(255, 255, 255);
        doc.text('CRASH LENS', m, 8);
        doc.setFont('helvetica', 'normal');
        doc.text('Before/After Batch Evaluation Report', pw - m, 8, { align: 'right' });
    }
    function drawPageFooter(page, total) {
        doc.setDrawColor(200, 200, 200); doc.setLineWidth(0.3);
        doc.line(m, ph - 15, pw - m, ph - 15);
        doc.setFontSize(7); setColor(C.gray);
        var attr = typeof getReportAttribution === 'function' ? getReportAttribution() : 'CRASH LENS';
        doc.text('Generated by ' + attr + ' | ' + generatedDate, m, ph - 10);
        doc.text('Page ' + page + ' of ' + total, pw - m, ph - 10, { align: 'right' });
    }
    function newPage() {
        if (pageNum > 0) doc.addPage();
        pageNum++;
        drawPageHeader();
        y = m + headerH + 5;
    }
    function checkPageBreak(needed) {
        if (y + (needed || 20) > safeBottom) { newPage(); return true; }
        return false;
    }
    function addSectionTitle(title, color) {
        checkPageBreak(15);
        var rgb = hexToRgb(color || C.primary);
        doc.setFillColor(rgb.r, rgb.g, rgb.b);
        doc.rect(m, y - 4, 3, 10, 'F');
        doc.setFontSize(14); doc.setFont('helvetica', 'bold');
        doc.setTextColor(rgb.r, rgb.g, rgb.b);
        doc.text(cleanText(title), m + 6, y + 3);
        y += 12;
    }
    function addSubsectionTitle(title, color) {
        checkPageBreak(12);
        doc.setFontSize(11); doc.setFont('helvetica', 'bold');
        setColor(color || C.text);
        doc.text(cleanText(title), m, y);
        y += 7;
    }
    function drawKPICard(x, yy, width, height, value, label, color) {
        var rgb = hexToRgb(color);
        doc.setFillColor(rgb.r, rgb.g, rgb.b);
        doc.roundedRect(x, yy, width, height, 2, 2, 'F');
        doc.setFontSize(16); doc.setFont('helvetica', 'bold'); doc.setTextColor(255, 255, 255);
        doc.text(String(value), x + width / 2, yy + height / 2 - 2, { align: 'center' });
        doc.setFontSize(7); doc.setFont('helvetica', 'normal');
        var lines = doc.splitTextToSize(cleanText(label), width - 4);
        doc.text(lines, x + width / 2, yy + height / 2 + 8, { align: 'center' });
    }
    function drawSeverityBar(severity, maxWidth) {
        checkPageBreak(18);
        var total = (severity.K || 0) + (severity.A || 0) + (severity.B || 0) + (severity.C || 0) + (severity.O || 0);
        if (total === 0) return;
        var barH = 8; var curX = m;
        var segs = [
            { key: 'K', color: C.fatal, label: 'Fatal' }, { key: 'A', color: C.fatalLight, label: 'Serious' },
            { key: 'B', color: C.moderate, label: 'Moderate' }, { key: 'C', color: C.minor, label: 'Minor' },
            { key: 'O', color: C.pdo, label: 'PDO' }
        ];
        segs.forEach(function(seg) {
            var count = severity[seg.key] || 0;
            if (count > 0) { var w = (count / total) * maxWidth; setFill(seg.color); doc.rect(curX, y, w, barH, 'F'); curX += w; }
        });
        doc.setDrawColor(200, 200, 200); doc.setLineWidth(0.3); doc.rect(m, y, maxWidth, barH, 'S');
        y += barH + 3;
        doc.setFontSize(7); var legendX = m;
        segs.forEach(function(seg) {
            var count = severity[seg.key] || 0;
            if (count > 0) { setFill(seg.color); doc.rect(legendX, y, 6, 4, 'F'); setColor(C.text); doc.text(seg.label + ': ' + count, legendX + 8, y + 3); legendX += 35; }
        });
        y += 10;
    }
    function ratingColor(label) {
        var map = { 'Highly Effective': C.successLight, 'Effective': '#65a30d', 'Marginal': '#ca8a04', 'Ineffective': C.warning, 'Negative Impact': C.danger };
        return map[label] || C.gray;
    }
    // Row background tint based on effectiveness rating
    function ratingRowBg(label) {
        var map = { 'Highly Effective': '#f0fdf4', 'Effective': '#f0fdf4', 'Marginal': '#fefce8', 'Ineffective': '#fef2f2', 'Negative Impact': '#fef2f2' };
        return map[label] || C.lightBg;
    }

    // ================================================================
    // PAGE 1: COVER PAGE
    // ================================================================
    newPage();
    y = 55;
    doc.setFontSize(26); doc.setFont('helvetica', 'bold'); setColor(C.primary);
    doc.text('BATCH BEFORE/AFTER STUDY', pw / 2, y, { align: 'center' });
    y += 10;
    doc.setFontSize(14); doc.setFont('helvetica', 'normal'); setColor(C.textLight);
    doc.text('Countermeasure Effectiveness Evaluation Report', pw / 2, y, { align: 'center' });
    // Decorative rule
    y += 6;
    var ruleRgb = hexToRgb(C.primary);
    doc.setDrawColor(ruleRgb.r, ruleRgb.g, ruleRgb.b); doc.setLineWidth(0.8);
    doc.line(pw / 2 - 40, y, pw / 2 + 40, y);
    y += 4;
    doc.setFontSize(10); doc.setFont('helvetica', 'normal'); setColor(C.textLight);
    doc.text(generatedDate, pw / 2, y, { align: 'center' });

    // KPI Cards Row
    y += 18;
    var cardW = 35; var cardH = 26; var cardGap = 5;
    var totalW = cardW * 5 + cardGap * 4;
    var cardX = (pw - totalW) / 2;
    drawKPICard(cardX, y, cardW, cardH, sum.totalAnalyzed, 'Locations Analyzed', C.primary);
    cardX += cardW + cardGap;
    drawKPICard(cardX, y, cardW, cardH, sum.avgCrashReduction.toFixed(1) + '%', 'Avg Reduction', sum.avgCrashReduction > 0 ? C.success : C.danger);
    cardX += cardW + cardGap;
    drawKPICard(cardX, y, cardW, cardH, sum.avgCMF !== null ? sum.avgCMF.toFixed(3) : 'N/A', 'Average CMF', sum.avgCMF !== null && sum.avgCMF < 1 ? C.success : C.primaryLight);
    cardX += cardW + cardGap;
    var cpLabel = sum.crashesPrevented >= 0 ? 'Net Prevented' : 'Net Increase';
    drawKPICard(cardX, y, cardW, cardH, Math.abs(sum.crashesPrevented), cpLabel, sum.crashesPrevented >= 0 ? C.secondary : C.danger);
    cardX += cardW + cardGap;
    drawKPICard(cardX, y, cardW, cardH, sum.significantPct.toFixed(0) + '%', 'Significant', C.primaryLight);
    y += cardH + 20;

    // Report details box
    setFill(C.lightBg);
    var borderRgb = hexToRgb(C.border); doc.setDrawColor(borderRgb.r, borderRgb.g, borderRgb.b);
    doc.roundedRect(m + 20, y, cw - 40, 48, 3, 3, 'FD');
    y += 10;
    doc.setFontSize(10); doc.setFont('helvetica', 'bold'); setColor(C.text);
    doc.text('Report Details', pw / 2, y, { align: 'center' });
    y += 8;
    doc.setFont('helvetica', 'normal'); doc.setFontSize(9);
    doc.text('Analysis Radius: ' + s.globalRadiusFt + ' ft | Confidence Level: ' + (s.confidenceLevel * 100) + '%', pw / 2, y, { align: 'center' });
    y += 6;
    doc.text('EPDO Weights: ' + epdoInfo.name + ' (K=' + epdoInfo.weights.K + ', A=' + epdoInfo.weights.A + ', B=' + epdoInfo.weights.B + ', C=' + epdoInfo.weights.C + ', O=' + epdoInfo.weights.O + ')', pw / 2, y, { align: 'center' });
    y += 6;
    doc.text('Method: Empirical Bayes (simplified) | Significance: Two-tailed z-test (Poisson)', pw / 2, y, { align: 'center' });

    // ================================================================
    // PAGE 2: TABLE OF CONTENTS (placeholder — page numbers filled after full render)
    // ================================================================
    newPage();
    var tocPageNum = pageNum;
    addSectionTitle('Table of Contents');
    y += 4;
    var tocSections = [
        'Executive Summary', 'Visual Analysis', 'Location Summary Table',
        'Individual Location Results', 'How to Read This Report', 'Methodology Notes'
    ];
    var tocYPositions = [];
    doc.setFontSize(11); doc.setFont('helvetica', 'normal'); setColor(C.text);
    tocSections.forEach(function(sec, i) {
        var dotLeader = ' . . . . . . . . . . . . . . . . . . . . . . . . . . . . . . . . . . . . . .';
        doc.text((i + 1) + '.  ' + sec, m + 5, y);
        tocYPositions.push({ section: sec, yPos: y });
        doc.setFont('helvetica', 'normal'); setColor(C.textLight);
        doc.text(dotLeader, m + 65, y);
        setColor(C.text);
        y += 9;
    });

    // ================================================================
    // PAGE 3: EXECUTIVE SUMMARY
    // ================================================================
    newPage();
    sectionPages['Executive Summary'] = pageNum;
    addSectionTitle('Executive Summary');

    // Narrative summary paragraph
    // Use pre-computed fewerCrashesCount: locations where afterTotal < beforeTotal (excludes 0/0 ties)
    var improved = sum.fewerCrashesCount;
    var pctImproved = successful.length > 0 ? (improved / successful.length * 100).toFixed(0) : '0';
    var narrative = 'This evaluation analyzed ' + sum.totalAnalyzed + ' locations where safety countermeasures were installed.';
    if (sum.avgCrashReduction > 0) {
        narrative += ' Overall, treated locations experienced a ' + sum.avgCrashReduction.toFixed(1) + '% average reduction in crash frequency, with ' + improved + ' of ' + successful.length + ' locations (' + pctImproved + '%) showing improvement.';
    } else if (sum.avgCrashReduction < 0) {
        narrative += ' Overall, treated locations experienced a ' + Math.abs(sum.avgCrashReduction).toFixed(1) + '% average increase in crash frequency. Only ' + improved + ' of ' + successful.length + ' locations (' + pctImproved + '%) showed improvement.';
    } else {
        narrative += ' On average, crash frequency remained unchanged across ' + successful.length + ' locations.';
    }
    if (sum.crashesPrevented > 0) {
        narrative += ' An estimated ' + sum.crashesPrevented + ' crashes were prevented across all treated sites.';
    }
    doc.setFontSize(9); doc.setFont('helvetica', 'normal'); setColor(C.text);
    var narrativeLines = doc.splitTextToSize(cleanText(narrative), cw);
    doc.text(narrativeLines, m, y);
    y += narrativeLines.length * 4.5 + 6;

    // Key Takeaways box
    var takeaways = [];
    takeaways.push(improved + ' of ' + successful.length + ' locations (' + pctImproved + '%) had fewer crashes after treatment.');
    if (sum.avgCrashReduction > 0) takeaways.push('Average crash reduction: ' + sum.avgCrashReduction.toFixed(1) + '%.');
    else if (sum.avgCrashReduction < 0) takeaways.push('Average crash increase: ' + Math.abs(sum.avgCrashReduction).toFixed(1) + '%.');
    var best = successful.slice().sort(function(a, b) { return a.changePct - b.changePct; })[0];
    if (best && best.changePct < 0) takeaways.push('Best result: ' + cleanText(best.locationName) + ' - ' + Math.abs(best.changePct).toFixed(1) + '% reduction.');
    var sigCount = successful.filter(function(r) { return r.isSignificant; }).length;
    if (sigCount > 0) takeaways.push(sigCount + ' location(s) showed statistically significant results.');
    var takeawayH = 8 + takeaways.length * 5.5;
    checkPageBreak(takeawayH + 5);
    setFill('#eff6ff');
    var tkBorder = hexToRgb('#bfdbfe'); doc.setDrawColor(tkBorder.r, tkBorder.g, tkBorder.b); doc.setLineWidth(0.4);
    doc.roundedRect(m, y, cw, takeawayH, 2, 2, 'FD');
    doc.setFontSize(9); doc.setFont('helvetica', 'bold'); setColor('#1e40af');
    doc.text('Key Takeaways', m + 5, y + 5.5);
    doc.setFontSize(8); doc.setFont('helvetica', 'normal'); setColor(C.text);
    var tkY = y + 11;
    takeaways.forEach(function(t) { doc.text('  *  ' + t, m + 5, tkY); tkY += 5.5; });
    y += takeawayH + 6;

    // Top Performers callout box
    var topPerformers = successful.filter(function(r) { return r.changePct < 0; })
        .sort(function(a, b) { return a.changePct - b.changePct; }).slice(0, 3);
    if (topPerformers.length > 0) {
        var tpH = 8 + topPerformers.length * 5.5;
        checkPageBreak(tpH + 5);
        setFill('#dcfce7');
        var tpBorder = hexToRgb('#86efac'); doc.setDrawColor(tpBorder.r, tpBorder.g, tpBorder.b); doc.setLineWidth(0.4);
        doc.roundedRect(m, y, cw / 2 - 3, tpH, 2, 2, 'FD');
        doc.setFontSize(8); doc.setFont('helvetica', 'bold'); setColor('#065f46');
        doc.text('Top Performers', m + 5, y + 5.5);
        doc.setFontSize(7); doc.setFont('helvetica', 'normal'); setColor(C.text);
        var tpY = y + 11;
        topPerformers.forEach(function(r) {
            var crf = r.crf !== null ? r.crf.toFixed(1) + '% CRF' : '';
            doc.text(cleanText(r.locationName).substring(0, 35) + ' - ' + crf, m + 5, tpY);
            tpY += 5.5;
        });

        // Locations Requiring Review callout box (side by side)
        var negImpact = successful.filter(function(r) { return r.cmf !== null && r.cmf > 1.10; })
            .sort(function(a, b) { return b.cmf - a.cmf; }).slice(0, 3);
        if (negImpact.length > 0) {
            var niH = 8 + negImpact.length * 5.5;
            var niBoxH = Math.max(tpH, niH);
            setFill('#fef2f2');
            var niBorder = hexToRgb('#fca5a5'); doc.setDrawColor(niBorder.r, niBorder.g, niBorder.b);
            doc.roundedRect(m + cw / 2 + 3, y, cw / 2 - 3, niBoxH, 2, 2, 'FD');
            doc.setFontSize(8); doc.setFont('helvetica', 'bold'); setColor('#991B1B');
            doc.text('Locations Requiring Review', m + cw / 2 + 8, y + 5.5);
            doc.setFontSize(7); doc.setFont('helvetica', 'normal'); setColor(C.text);
            var niY = y + 11;
            negImpact.forEach(function(r) {
                doc.text(cleanText(r.locationName).substring(0, 30) + ' - CMF ' + r.cmf.toFixed(3), m + cw / 2 + 8, niY);
                niY += 5.5;
            });
            y += Math.max(tpH, niH) + 6;
        } else {
            y += tpH + 6;
        }
    }

    // Effectiveness Distribution table
    addSubsectionTitle('Effectiveness Distribution');
    var effLabels = ['Highly Effective', 'Effective', 'Marginal', 'Ineffective', 'Negative Impact'];
    var effDescs = ['CMF < 0.70', 'CMF 0.70-0.90', 'CMF 0.90-1.00', 'CMF 1.00-1.10', 'CMF > 1.10'];
    var effData = effLabels.map(function(label, i) { return [label, effDescs[i], String(sum.byEffectiveness[label] || 0)]; });
    var effColors = [C.successLight, '#65a30d', '#ca8a04', C.warning, C.danger];
    doc.autoTable({
        startY: y, head: [['Rating', 'CMF Range', 'Count']], body: effData,
        margin: { left: m, right: m }, styles: { fontSize: 9, cellPadding: 3 },
        headStyles: { fillColor: hexToRgb(C.primary), textColor: [255, 255, 255] },
        alternateRowStyles: { fillColor: hexToRgb(C.lightBg) },
        columnStyles: { 0: { cellWidth: 50 }, 2: { halign: 'center', cellWidth: 25, fontStyle: 'bold' } },
        didParseCell: function(data) {
            if (data.column.index === 0 && data.section === 'body') { data.cell.styles.textColor = hexToRgb(C.text); data.cell.styles.fontStyle = 'bold'; }
        },
        didDrawCell: function(data) {
            if (data.column.index === 0 && data.section === 'body' && data.row.index < effColors.length) {
                var accentRgb = hexToRgb(effColors[data.row.index]);
                doc.setFillColor(accentRgb.r, accentRgb.g, accentRgb.b);
                doc.rect(data.cell.x, data.cell.y, 2.5, data.cell.height, 'F');
            }
        }
    });
    y = doc.lastAutoTable.finalY + 8;

    // Significance and severity comparison
    addSubsectionTitle('Statistical Significance');
    doc.setFontSize(9); doc.setFont('helvetica', 'normal'); setColor(C.text);
    doc.text(sum.significantCount + ' of ' + sum.totalAnalyzed + ' locations (' + sum.significantPct.toFixed(0) + '%) showed statistically significant crash changes at ' + (s.confidenceLevel * 100) + '% confidence.', m, y);
    y += 6;
    var cpText = sum.crashesPrevented >= 0
        ? 'Net crashes prevented: ' + sum.crashesPrevented : 'Net crash increase: ' + Math.abs(sum.crashesPrevented);
    doc.text(cpText + ' (true net: sum of before minus after across all locations).', m, y);
    y += 10;

    if (successful.length > 0) {
        addSubsectionTitle('Aggregated Severity: Before vs After');
        var aggBefore = { K: 0, A: 0, B: 0, C: 0, O: 0 };
        var aggAfter = { K: 0, A: 0, B: 0, C: 0, O: 0 };
        successful.forEach(function(r) {
            ['K', 'A', 'B', 'C', 'O'].forEach(function(sev) { aggBefore[sev] += (r.beforeStats[sev] || 0); aggAfter[sev] += (r.afterStats[sev] || 0); });
        });
        doc.setFontSize(8); doc.setFont('helvetica', 'bold'); setColor(C.fatalLight);
        doc.text('BEFORE', m, y); y += 2; drawSeverityBar(aggBefore, cw * 0.7);
        doc.setFontSize(8); doc.setFont('helvetica', 'bold'); setColor(C.successLight);
        doc.text('AFTER', m, y); y += 2; drawSeverityBar(aggAfter, cw * 0.7);
    }

    // By countermeasure type
    var typeKeys = Object.keys(sum.byType);
    if (typeKeys.length > 1) {
        checkPageBreak(40);
        addSubsectionTitle('Performance by Countermeasure Type');
        var typeRows = typeKeys.sort().map(function(t) {
            var info = sum.byType[t];
            var avgCmf = info.cmfCount > 0 ? (info.totalCMF / info.cmfCount).toFixed(3) : 'N/A';
            var avgChange = (info.evaluableCount || 0) > 0 ? (info.totalChange / info.evaluableCount).toFixed(1) + '%' : 'N/A';
            return [t, String(info.count), avgCmf, avgChange];
        });
        doc.autoTable({
            startY: y, head: [['Countermeasure Type', 'Locations', 'Avg CMF', 'Avg Change']], body: typeRows,
            margin: { left: m, right: m }, styles: { fontSize: 9, cellPadding: 2.5 },
            headStyles: { fillColor: hexToRgb(C.secondary), textColor: [255, 255, 255] },
            alternateRowStyles: { fillColor: hexToRgb(C.lightBg) },
            columnStyles: { 1: { halign: 'center', cellWidth: 25 }, 2: { halign: 'center', cellWidth: 25 }, 3: { halign: 'center', cellWidth: 25 } }
        });
        y = doc.lastAutoTable.finalY + 10;
    }

    // ================================================================
    // VISUAL ANALYSIS PAGE — Chart Images
    // ================================================================
    function captureChart(canvasId) {
        var canvas = document.getElementById(canvasId);
        if (!canvas || canvas.width === 0 || canvas.height === 0) return null;
        try { return canvas.toDataURL('image/png'); } catch (e) { return null; }
    }
    var chartBar = captureChart('batchBABarChart');
    var chartCMF = captureChart('batchBACMFChart');
    var chartSev = captureChart('batchBASeverityChart');
    var chartScatter = captureChart('batchBAScatterChart');
    var chartByType = captureChart('batchBACMFByTypeChart');
    var hasCharts = chartBar || chartCMF || chartSev || chartScatter;

    if (hasCharts) {
        newPage();
        sectionPages['Visual Analysis'] = pageNum;
        addSectionTitle('Visual Analysis');
        var halfW = (cw - 6) / 2; var chartH = 55; var chartTitleH = 8;
        if (chartBar) {
            doc.setFontSize(8); doc.setFont('helvetica', 'bold'); setColor(C.primary);
            doc.text('Crash Rate: Before vs After', m, y + 4);
            try { doc.addImage(chartBar, 'PNG', m, y + chartTitleH, halfW, chartH); } catch (e) { /* skip */ }
        }
        if (chartCMF) {
            doc.setFontSize(8); doc.setFont('helvetica', 'bold'); setColor(C.primary);
            doc.text('Safety Score Distribution', m + halfW + 6, y + 4);
            try { doc.addImage(chartCMF, 'PNG', m + halfW + 6, y + chartTitleH, halfW, chartH); } catch (e) { /* skip */ }
        }
        y += chartTitleH + chartH + 8;
        checkPageBreak(chartTitleH + chartH + 10);
        if (chartSev) {
            doc.setFontSize(8); doc.setFont('helvetica', 'bold'); setColor(C.primary);
            doc.text('Severity Comparison', m, y + 4);
            try { doc.addImage(chartSev, 'PNG', m, y + chartTitleH, halfW, chartH); } catch (e) { /* skip */ }
        }
        if (chartScatter) {
            doc.setFontSize(8); doc.setFont('helvetica', 'bold'); setColor(C.primary);
            doc.text('Improvement Scatter Plot', m + halfW + 6, y + 4);
            try { doc.addImage(chartScatter, 'PNG', m + halfW + 6, y + chartTitleH, halfW, chartH); } catch (e) { /* skip */ }
        }
        y += chartTitleH + chartH + 8;
        if (chartByType) {
            checkPageBreak(chartTitleH + 45);
            doc.setFontSize(8); doc.setFont('helvetica', 'bold'); setColor(C.primary);
            doc.text('Average Safety Score by Treatment Type', m, y + 4);
            try { doc.addImage(chartByType, 'PNG', m, y + chartTitleH, cw, 40); } catch (e) { /* skip */ }
            y += chartTitleH + 40 + 8;
        }
    }

    // ================================================================
    // Pass context to details module (table, cards, methodology, TOC fill, save)
    // ================================================================
    CL.batchBA._pdfCtx = {
        doc: doc, y: y, pageNum: pageNum,
        m: m, pw: pw, ph: ph, cw: cw, C: C,
        s: s, sum: sum, successful: successful, epdoInfo: epdoInfo,
        safeBottom: safeBottom, generatedDate: generatedDate, dateStamp: dateStamp,
        sectionPages: sectionPages, tocPageNum: tocPageNum, tocYPositions: tocYPositions,
        hexToRgb: hexToRgb, setColor: setColor, setFill: setFill, cleanText: cleanText,
        drawPageHeader: drawPageHeader, drawPageFooter: drawPageFooter,
        ratingColor: ratingColor, ratingRowBg: ratingRowBg,
        newPage: function() {
            var ctx = CL.batchBA._pdfCtx;
            y = ctx.y; pageNum = ctx.pageNum; newPage(); ctx.y = y; ctx.pageNum = pageNum;
        },
        checkPageBreak: function(needed) {
            var ctx = CL.batchBA._pdfCtx;
            y = ctx.y; var result = checkPageBreak(needed); ctx.y = y; ctx.pageNum = pageNum; return result;
        },
        addSectionTitle: function(title, color) {
            var ctx = CL.batchBA._pdfCtx; y = ctx.y; addSectionTitle(title, color); ctx.y = y;
        },
        addSubsectionTitle: function(title, color) {
            var ctx = CL.batchBA._pdfCtx; y = ctx.y; addSubsectionTitle(title, color); ctx.y = y;
        }
    };
    CL.batchBA._exportPDFDetails();
};

